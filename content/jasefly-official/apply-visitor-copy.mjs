async function main() {
  const resume = process.env.RESUME_FROM || ''
  const stopAfter = process.env.STOP_AFTER || ''
  const only = (process.env.ONLY_SLUGS || '')
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
  const skipUntil = (slug) => {
    if (!resume) return false
    const order = [
      'features',
      'workflow',
      'cms-modules',
      'mcp',
      'shared-hosting',
      'docs',
      'updates',
      'about',
      'contact',
      'privacy',
      'blog',
    ]
    const ri = order.indexOf(resume === 'modules' ? 'cms-modules' : resume)
    const si = order.indexOf(slug)
    return ri >= 0 && si >= 0 && si < ri
  }
  const pastStop = (slug) => {
    if (!stopAfter) return false
    const order = [
      'features',
      'workflow',
      'cms-modules',
      'mcp',
      'shared-hosting',
      'docs',
      'updates',
      'about',
      'contact',
      'privacy',
      'blog',
    ]
    const zi = order.indexOf(stopAfter === 'modules' ? 'cms-modules' : stopAfter)
    const si = order.indexOf(slug)
    return zi >= 0 && si >= 0 && si > zi
  }

  const pagesIndex = await listPages()

  if (!resume && only.length === 0) {
    await patchSingletonsAndNav()
    await patchHome(pagesIndex)
  } else {
    console.log('RESUME_FROM=', resume || '(none)', 'ONLY_SLUGS=', only.join(',') || '(all)', 'STOP_AFTER=', stopAfter || '(none)')
  }
  for (const page of pages) {
    if (only.length && !only.includes(page.slug)) {
      console.log('skip(only)', page.slug)
      continue
    }
    if (skipUntil(page.slug)) {
      console.log('skip', page.slug)
      continue
    }
    if (pastStop(page.slug)) {
      console.log('stop before', page.slug)
      break
    }
    n = 0
    await putPage(page, pagesIndex)
  }
  if (!resume && only.length === 0 && !stopAfter) {
    n = 0
    await ensureApiDocs(pagesIndex)
    await patchTerms(pagesIndex)
    await patchBlogPostsLight()
  }
  console.log('DONE visitor copy apply')
}

main().catch((e) => {
  console.error(e.message || e)
  if (e.payload) console.error(JSON.stringify(e.payload, null, 2))
  process.exit(1)
})
